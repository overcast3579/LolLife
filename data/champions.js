export function getChampionById(id) {
  return CHAMPIONS.find(c => c.id === id) || null;
}

export function getMasteryInfo(points) {
  let current = MASTERY_LEVELS[0];
  for (let m of MASTERY_LEVELS) {
    if (points >= m.minPoints) {
      current = m;
    } else {
      break;
    }
  }
  return current;
}
